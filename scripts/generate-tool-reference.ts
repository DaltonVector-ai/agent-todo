/**
 * Generate docs/tool-reference.md from MCP zod tool schemas.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CORE_TOOL_NAMES, TOOL_DESCRIPTIONS } from "../packages/mcp/src/schemas.ts";
import {
	ADMIN_DESCRIPTIONS,
	ADMIN_TOOL_NAMES,
	PLAN_DESCRIPTIONS,
	PLAN_TOOL_NAMES,
} from "../packages/mcp/src/schemas-plan-admin.ts";

const root = join(import.meta.dir, "..");
const out = join(root, "docs/tool-reference.md");

function section(
	title: string,
	names: readonly string[],
	descriptions: Record<string, string>,
): string {
	const lines = names.map((name) => `- **\`${name}\`** — ${descriptions[name] ?? ""}`);
	return `## ${title}\n\n${lines.join("\n")}\n`;
}

const body = `<!-- generated by scripts/generate-tool-reference.ts — do not edit by hand -->

# Tool reference

MCP tools exposed by \`agent-todo serve --mcp\`. Regenerate with \`bun run docs:tool-reference\`.

${section("Core toolset", CORE_TOOL_NAMES, TOOL_DESCRIPTIONS)}
${section("Plan toolset", PLAN_TOOL_NAMES, PLAN_DESCRIPTIONS)}
${section("Admin toolset", ADMIN_TOOL_NAMES, ADMIN_DESCRIPTIONS)}

## Optional

- **\`context_generate\`** — Draft context via client sampling (plan toolset / sampling).
`;

writeFileSync(out, body);
console.log(`Wrote ${out}`);
